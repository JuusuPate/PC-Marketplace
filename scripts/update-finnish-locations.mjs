import { writeFile } from "node:fs/promises";
const base =
  "https://api.stat.fi/classificationservice/open/api/classifications/v2/correspondenceTables/kunta_1_20260101%23maakunta_1_20260101/maps?content=data&format=json&meta=min";
async function download(lang) {
  const response = await fetch(`${base}&lang=${lang}`);
  if (!response.ok) throw new Error(`Statistics Finland: ${response.status}`);
  return response.json();
}
const [fi, sv] = await Promise.all([download("fi"), download("sv")]);
const translated = new Map(sv.map((row) => [row.sourceItem.code, row]));
const regions = new Map();
const municipalityCodes = new Set();
const name = (item, lang) => {
  const result = item.classificationItemNames.find((text) => text.lang === lang)?.name;
  if (!result) throw new Error(`Missing ${lang} name for ${item.code}`);
  return result;
};
for (const row of fi) {
  const other = translated.get(row.sourceItem.code);
  if (!other || other.targetItem.code !== row.targetItem.code || municipalityCodes.has(row.sourceItem.code))
    throw new Error("Inconsistent municipality mapping");
  municipalityCodes.add(row.sourceItem.code);
  const code = row.targetItem.code;
  if (!regions.has(code))
    regions.set(code, { code, fi: name(row.targetItem, "fi"), sv: name(other.targetItem, "sv"), municipalities: [] });
  regions
    .get(code)
    .municipalities.push([row.sourceItem.code, name(row.sourceItem, "fi"), name(other.sourceItem, "sv")]);
}
if (regions.size !== 19 || municipalityCodes.size !== 308 || sv.length !== 308)
  throw new Error("Unexpected 2026 classification size; inspect upstream data before updating");
const result = [...regions.values()].sort((a, b) => a.fi.localeCompare(b.fi, "fi"));
for (const region of result) region.municipalities.sort((a, b) => a[1].localeCompare(b[1], "fi"));
const body = `/** Statistics Finland, municipalities to regions 2026. Generated by scripts/update-finnish-locations.mjs.\n * Source: ${base}&lang=fi\n * Municipality tuples: [official code, Finnish name, Swedish name]. */\nexport interface FinnishRegion { code: string; fi: string; sv: string; municipalities: [string, string, string][]; }\nexport const FINNISH_REGIONS: FinnishRegion[] = ${JSON.stringify(result, null, 2)};\n`;
await writeFile(new URL("../apps/web/src/data/finnish-locations.ts", import.meta.url), body);
console.log(`Saved ${municipalityCodes.size} municipalities in ${regions.size} regions.`);
